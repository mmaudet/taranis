export const AVAILABLE_LANGS = ["fr", "en", "es", "it", "de"];

let CURRENT = "fr";

export function detectBrowserLang() {
    const raw = (typeof navigator !== "undefined" ? navigator.language : "en") || "en";
    const short = raw.toLowerCase().split("-")[0];
    return AVAILABLE_LANGS.includes(short) ? short : "en";
}

export function setLang(lang) {
    CURRENT = AVAILABLE_LANGS.includes(lang) ? lang : "en";
    if (typeof document !== "undefined") {
        document.documentElement.setAttribute("lang", CURRENT);
    }
}

export function currentLang() {
    return CURRENT;
}

export function t(key, fallback) {
    const bag = STRINGS[CURRENT] || STRINGS.en;
    if (bag[key] !== undefined) return bag[key];
    if (STRINGS.en[key] !== undefined) return STRINGS.en[key];
    return fallback !== undefined ? fallback : key;
}

// Populate all elements bearing data-i18n or data-i18n-attr attributes.
// Optionally accepts a root to update; defaults to the whole document.
export function applyI18n(root = document) {
    root.querySelectorAll("[data-i18n]").forEach(el => {
        el.textContent = t(el.getAttribute("data-i18n"));
    });
    root.querySelectorAll("[data-i18n-html]").forEach(el => {
        el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    root.querySelectorAll("[data-i18n-title]").forEach(el => {
        el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });
    root.querySelectorAll("[data-i18n-aria]").forEach(el => {
        el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
}
